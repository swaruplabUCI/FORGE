#!/usr/bin/env python3
# v2: auto-detect celltypist/scanvi prediction columns (cache invalidation)
"""
Multi-Sample Multiome MuData Construction Pipeline (CLI-enabled)
Combines RNA + ATAC samples into unified MuData object
"""

import numpy as np
import pandas as pd
import scanpy as sc
import mudata as md
import anndata as ad
from pathlib import Path
import warnings
import json
from h5ad_compat import sanitize_mudata
import gc
import shutil
from datetime import datetime
import psutil
import os
import argparse
import sys
import re

warnings.filterwarnings('ignore')

def log_memory(log_file):
    process = psutil.Process(os.getpid())
    mem_gb = process.memory_info().rss / 1024**3
    log_message(f"  Memory usage: {mem_gb:.2f} GB", log_file)

def log_message(message: str, log_file, level: str = "INFO"):
    """Log messages to file and console"""
    timestamp = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    log_entry = f"[{timestamp}] {level}: {message}"
    print(log_entry)
    with open(log_file, 'a') as f:
        f.write(log_entry + '\n')

def parse_args():
    parser = argparse.ArgumentParser(
        description='Build unified MuData from RNA and ATAC h5ad files'
    )

    parser.add_argument('--sample_map', type=str, required=True,
                       help='CSV file mapping sample_id,rna_file,atac_file (generated by Nextflow)')
    parser.add_argument('--scanvi_file', type=str, default=None,
                       help='Path to SCANVI predictions h5ad (optional)')
    parser.add_argument('--metadata_file', type=str, required=True,
                       help='Path to sample metadata CSV')

    parser.add_argument('--output_dir', type=str, required=True,
                       help='Output directory for MuData')
    parser.add_argument('--output_name', type=str, default='integrated.h5mu',
                       help='Output filename (default: integrated.h5mu)')

    parser.add_argument('--batch_size', type=int, default=10,
                       help='Batch size for concatenation (default: 10)')
    parser.add_argument('--min_retention', type=float, default=0.0,
                       help='Minimum RNA/ATAC overlap retention rate (default: 0.0)')
    parser.add_argument('--atac_annotations', type=str, default=None,
                       help='Path to annotated ATAC peak matrix h5ad (for transferring cell type labels)')

    return parser.parse_args()

# ============================================================================
# Sample pairing is now handled by the sample_map CSV from Nextflow.
# The Nextflow fail-fast join (main.nf) ensures only QC-passing, correctly
# paired RNA+ATAC samples reach this script.
# ============================================================================


def main():
    args = parse_args()
    
    # Setup directories
    OUTPUT_DIR = Path(args.output_dir)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    TEMP_DIR = OUTPUT_DIR / "temp_batches"
    TEMP_DIR.mkdir(exist_ok=True)
    
    LOG_FILE = OUTPUT_DIR / f"mudata_construction_{datetime.now().strftime('%Y%m%d_%H%M%S')}.log"
    
    log_message("="*80, LOG_FILE)
    log_message("MUDATA CONSTRUCTION PIPELINE", LOG_FILE)
    log_message("="*80, LOG_FILE)
    log_message(f"Sample map: {args.sample_map}", LOG_FILE)
    log_message(f"Metadata: {args.metadata_file}", LOG_FILE)
    log_message(f"Output: {OUTPUT_DIR / args.output_name}", LOG_FILE)

    # Load metadata
    log_message("\nLoading metadata...", LOG_FILE)
    metadata_df = pd.read_csv(args.metadata_file)
    log_message(f"Loaded {len(metadata_df)} entries", LOG_FILE)

    # ========================================================================
    # Load sample pairing map (generated by Nextflow from QC-passing pairs)
    # ========================================================================
    log_message("\n" + "="*80, LOG_FILE)
    log_message("LOADING SAMPLE PAIRING MAP", LOG_FILE)
    log_message("="*80, LOG_FILE)

    sample_map_df = pd.read_csv(args.sample_map)
    log_message(f"Sample map contains {len(sample_map_df)} paired samples", LOG_FILE)

    matched_pairs = []
    for _, row in sample_map_df.iterrows():
        sample_id = row['sample_id']
        rna_path = Path(row['rna_file'])
        atac_path = Path(row['atac_file'])
        # Nextflow stages files as symlinks in the work dir by name
        if not rna_path.exists():
            rna_path = Path('.') / rna_path.name
        if not atac_path.exists():
            atac_path = Path('.') / atac_path.name
        if not rna_path.exists():
            log_message(f"  ERROR: RNA file not found: {rna_path}", LOG_FILE, "ERROR")
            sys.exit(1)
        if not atac_path.exists():
            log_message(f"  ERROR: ATAC file not found: {atac_path}", LOG_FILE, "ERROR")
            sys.exit(1)
        matched_pairs.append((sample_id, rna_path, atac_path))
        log_message(f"  {sample_id}: RNA={rna_path.name}, ATAC={atac_path.name}", LOG_FILE)

    if len(matched_pairs) == 0:
        log_message("\nERROR: No sample pairs in sample map!", LOG_FILE, "ERROR")
        sys.exit(1)
    
    # ========================================================================
    # Load SCANVI predictions if provided
    # ========================================================================
    # Canonical cell-type precedence: scanvi > celltypist (aliases) > marker.
    # We write the chosen value under a unified column name 'cell_type' and
    # record provenance in 'cell_type_source' so downstream modules don't need
    # to juggle annotation-tool-specific column names.
    _CT_CANDIDATES = [
        ('scanvi_prediction', 'scanvi'),
        ('celltypist_prediction', 'celltypist'),
        ('cell_type_prediction', 'celltypist'),
        ('cell_type_marker', 'marker'),
    ]
    # Lookup keyed by (sample, stripped_barcode). Built by parsing the scanvi
    # h5ad's obs_names using the `batch`/`sample` column to strip the concat
    # suffix. Falls back to (None, stripped_bc) for sample-agnostic matches.
    scanvi_predictions = {}
    scanvi_source = None

    def _strip_gem(bc):
        return re.sub(r'-\d+$', '', str(bc))

    if args.scanvi_file and Path(args.scanvi_file).exists():
        log_message(f"\nLoading cell-type predictions from {args.scanvi_file}", LOG_FILE)
        try:
            scanvi_adata = sc.read_h5ad(args.scanvi_file)
            pred_col = None
            for candidate, source in _CT_CANDIDATES:
                if candidate in scanvi_adata.obs.columns:
                    vals = scanvi_adata.obs[candidate].dropna().unique()
                    if len(vals) > 1 or (len(vals) == 1 and vals[0] != 'Unknown'):
                        pred_col = candidate
                        scanvi_source = source
                        break
            if pred_col:
                sample_col = None
                for c in ('batch', 'sample', 'sample_id'):
                    if c in scanvi_adata.obs.columns:
                        sample_col = c
                        break
                samples_series = (
                    scanvi_adata.obs[sample_col].astype(str).values
                    if sample_col is not None else [''] * scanvi_adata.n_obs
                )
                preds_series = scanvi_adata.obs[pred_col].astype(object).values
                for obs_name, sample, pred in zip(
                    scanvi_adata.obs_names, samples_series, preds_series
                ):
                    obs_name = str(obs_name)
                    # scanpy.concat(index_unique='-') appends "-{batch}" to each barcode
                    if sample and obs_name.endswith(f'-{sample}'):
                        raw = obs_name[: -(len(sample) + 1)]
                    else:
                        raw = obs_name
                    stripped = _strip_gem(raw)
                    scanvi_predictions[(str(sample), stripped)] = pred
                    # Sample-agnostic fallback for single-sample/untagged inputs
                    scanvi_predictions[('', stripped)] = pred
                n_unique = len({p for p in preds_series if not pd.isna(p)})
                log_message(
                    f"✓ Loaded predictions from '{pred_col}' (source={scanvi_source}) "
                    f"for {scanvi_adata.n_obs} cells, {n_unique} unique cell types; "
                    f"sample_col='{sample_col}'",
                    LOG_FILE,
                )
        except Exception as e:
            log_message(f"⚠ Could not load cell-type file: {e}", LOG_FILE, "WARN")
    
    # ========================================================================
    # NEW: Process MATCHED sample pairs
    # ========================================================================
    log_message("\n" + "="*80, LOG_FILE)
    log_message("PROCESSING MATCHED SAMPLE PAIRS", LOG_FILE)
    log_message("="*80, LOG_FILE)
    
    mudata_list = []
    sample_stats = []
    
    for idx, (sample_id, rna_file, atac_file) in enumerate(matched_pairs, 1):
        log_message(f"\n[{idx}/{len(matched_pairs)}] Processing {sample_id}...", LOG_FILE)
        log_message(f"  RNA:  {rna_file.name}", LOG_FILE)
        log_message(f"  ATAC: {atac_file.name}", LOG_FILE)
        
        try:
            # Load data
            rna_adata = sc.read_h5ad(rna_file)
            atac_adata = sc.read_h5ad(atac_file)
            
            log_message(f"  RNA cells: {rna_adata.n_obs:,}", LOG_FILE)
            log_message(f"  ATAC cells: {atac_adata.n_obs:,}", LOG_FILE)
            
            # ============================================================
            # FIX-P0-5 (C2): Smart barcode matching with normalization
            # ============================================================
            rna_sample_bc = str(rna_adata.obs_names[0])
            atac_sample_bc = str(atac_adata.obs_names[0])

            log_message(f"  RNA barcode example: {rna_sample_bc}", LOG_FILE)
            log_message(f"  ATAC barcode example: {atac_sample_bc}", LOG_FILE)

            # FIX-P0-5: Normalize barcodes by stripping -N suffix before matching
            # This handles 10x multiome where RNA has '-1' suffix but ATAC does not
            def _strip_suffix(bc):
                return re.sub(r'-\d+$', '', str(bc))

            rna_raw = list(rna_adata.obs_names)
            atac_raw = list(atac_adata.obs_names)
            rna_normalized = [_strip_suffix(bc) for bc in rna_raw]
            atac_normalized = [_strip_suffix(bc) for bc in atac_raw]

            # Build lookup: normalized → original index
            rna_norm_to_idx = {bc: i for i, bc in enumerate(rna_normalized)}
            atac_norm_to_idx = {bc: i for i, bc in enumerate(atac_normalized)}

            common_normalized = sorted(set(rna_normalized) & set(atac_normalized))

            if len(common_normalized) > 0:
                # Use normalized matching — subset to common cells via original indices
                rna_idx = [rna_norm_to_idx[bc] for bc in common_normalized]
                atac_idx = [atac_norm_to_idx[bc] for bc in common_normalized]
                rna_adata = rna_adata[rna_idx, :].copy()
                atac_adata = atac_adata[atac_idx, :].copy()
                # Assign consistent barcode names (use normalized form)
                rna_adata.obs_names = common_normalized
                atac_adata.obs_names = common_normalized
                common_barcodes = common_normalized

                # FIX-P0-5: Warn if join yield is suspiciously low
                join_yield = len(common_barcodes) / min(len(rna_raw), len(atac_raw))
                if join_yield < 0.10:
                    log_message(
                        f"  ⚠ Very low RNA-ATAC barcode overlap ({join_yield*100:.1f}%) for {sample_id}. "
                        f"Check that RNA and ATAC data come from the same multiome experiment.",
                        LOG_FILE, "WARN"
                    )
                log_message(f"  ✓ {len(common_barcodes):,} cells matched via normalized barcodes", LOG_FILE)
            else:
                # No overlap even after normalization — fall back to positional matching
                log_message("  ⚠ No barcode overlap after normalization - attempting positional matching", LOG_FILE, "WARN")
                log_message("  ⚠ WARNING: Positional matching assumes cells are in the same order!", LOG_FILE, "WARN")

                n_cells = min(rna_adata.n_obs, atac_adata.n_obs)
                synthetic_barcodes = [f"{sample_id}:cell_{i:06d}" for i in range(n_cells)]

                rna_adata = rna_adata[:n_cells, :].copy()
                atac_adata = atac_adata[:n_cells, :].copy()
                rna_adata.obs_names = synthetic_barcodes
                atac_adata.obs_names = synthetic_barcodes
                common_barcodes = synthetic_barcodes

                log_message(f"  ✓ Created {len(common_barcodes)} positionally matched cell pairs", LOG_FILE)

            if len(common_barcodes) == 0:
                log_message(f"  ⚠ Still no overlapping cells, skipping", LOG_FILE, "WARN")
                continue
            
            # Subset to common cells
            rna_sub = rna_adata[common_barcodes, :].copy()
            atac_sub = atac_adata[common_barcodes, :].copy()
            
            # Write canonical 'cell_type' + provenance on the RNA modality only
            # (RNA-side labels come from scanvi_file). ATAC side is populated
            # separately below from the scATAnno-annotated peak matrix, since
            # ATAC and RNA annotations come from independent tools/references
            # and should not be conflated. On lookup miss, leave NaN (not a
            # literal 'Unknown' string) so downstream consumers can distinguish
            # unlabeled from a real 'Unknown' call.
            if scanvi_predictions:
                sid = str(sample_id)
                cell_types = [
                    scanvi_predictions.get((sid, bc),
                        scanvi_predictions.get(('', bc), np.nan))
                    for bc in common_barcodes
                ]
                n_matched = sum(1 for ct in cell_types if not pd.isna(ct))
                src = scanvi_source or 'unknown'
                rna_sub.obs['cell_type'] = cell_types
                rna_sub.obs['cell_type_source'] = src
                log_message(
                    f"  RNA cell_type lookup matched {n_matched}/{len(common_barcodes)} barcodes",
                    LOG_FILE,
                )
            
            # Make barcodes globally unique across samples
            new_barcodes = [f"{sample_id}:{bc}" for bc in common_barcodes]
            rna_sub.obs_names = new_barcodes
            atac_sub.obs_names = new_barcodes
            
            # Create MuData
            mdata = md.MuData({'rna': rna_sub, 'atac': atac_sub})
            mdata.obs['sample_id'] = sample_id
            mdata.obs['sample_idx'] = idx
            
            mudata_list.append(mdata)
            
            retention = len(common_barcodes) / min(rna_adata.n_obs, atac_adata.n_obs)
            sample_stats.append({
                'sample_id': sample_id,
                'n_rna': rna_adata.n_obs,
                'n_atac': atac_adata.n_obs,
                'n_multiome': len(common_barcodes),
                'retention_rate': retention
            })
            
            log_message(f"  ✓ {len(common_barcodes):,} cells ({retention*100:.1f}% retention)", LOG_FILE)
            
            if idx % 10 == 0:
                log_memory(LOG_FILE)
                gc.collect()
                
        except Exception as e:
            log_message(f"  ✗ Error: {e}", LOG_FILE, "ERROR")
            import traceback
            log_message(traceback.format_exc(), LOG_FILE, "ERROR")
            continue
    
    log_message(f"\n✓ Successfully processed {len(mudata_list)} sample pairs", LOG_FILE)
    
    if len(mudata_list) == 0:
        log_message("\n❌ ERROR: No valid MuData objects created!", LOG_FILE, "ERROR")
        sys.exit(1)
    
    # ========================================================================
    # Concatenate samples
    # ========================================================================
    log_message("\n" + "="*80, LOG_FILE)
    log_message("CONCATENATING SAMPLES", LOG_FILE)
    log_message("="*80, LOG_FILE)
    log_memory(LOG_FILE)
    
    if len(mudata_list) == 1:
        log_message("Single sample — skipping concatenation", LOG_FILE)
        combined_mdata = mudata_list[0]
    elif len(mudata_list) < 50:
        log_message("Using direct concatenation", LOG_FILE)
        combined_mdata = md.concat(
            mudata_list,
            join='inner',
            merge='same',
            label=None,
            keys=None,
            index_unique=None
        )
    else:
        # Batched concatenation for large datasets
        log_message(f"Using batched concatenation (batch_size={args.batch_size})", LOG_FILE)
        
        n_batches = (len(mudata_list) + args.batch_size - 1) // args.batch_size
        batch_files = []
        
        for batch_idx in range(n_batches):
            start_idx = batch_idx * args.batch_size
            end_idx = min((batch_idx + 1) * args.batch_size, len(mudata_list))
            batch_mdatas = mudata_list[start_idx:end_idx]
            
            batch_combined = md.concat(
                batch_mdatas,
                join='inner',
                merge='same',
                label=None,
                keys=None,
                index_unique=None
            )
            
            batch_file = TEMP_DIR / f"batch_{batch_idx:03d}.h5mu"
            sanitize_mudata(batch_combined, batch_file)
            batch_combined.write_h5mu(batch_file)
            batch_files.append(batch_file)
            
            log_message(f"  Batch {batch_idx+1}/{n_batches}: {batch_combined.n_obs:,} cells", LOG_FILE)
            
            del batch_combined, batch_mdatas
            gc.collect()
        
        # Hierarchical merge
        current_files = batch_files
        merge_round = 1
        
        while len(current_files) > 1:
            next_files = []
            
            for i in range(0, len(current_files), 2):
                if i + 1 < len(current_files):
                    mdata1 = md.read_h5mu(current_files[i])
                    mdata2 = md.read_h5mu(current_files[i+1])
                    
                    merged = md.concat([mdata1, mdata2], join='inner', merge='same',
                                      label=None, keys=None, index_unique=None)
                    
                    merged_file = TEMP_DIR / f"merged_round{merge_round}_{i//2:03d}.h5mu"
                    sanitize_mudata(merged, merged_file)
                    merged.write_h5mu(merged_file)
                    next_files.append(merged_file)
                    
                    current_files[i].unlink()
                    current_files[i+1].unlink()
                    
                    del mdata1, mdata2, merged
                    gc.collect()
                else:
                    next_files.append(current_files[i])
            
            current_files = next_files
            merge_round += 1
            log_message(f"  Merge round {merge_round-1} complete: {len(next_files)} files", LOG_FILE)
        
        combined_mdata = md.read_h5mu(current_files[0])
        current_files[0].unlink()
    
    log_message(f"\n✓ Final MuData: {combined_mdata.n_obs:,} cells", LOG_FILE)
    log_memory(LOG_FILE)

    # ========================================================================
    # RNA-side cell_type: defensive fallback only
    # ========================================================================
    # Per-sample loop already wrote rna cell_type from scanvi_predictions.
    # Only fall back to legacy columns on the RNA modality (do NOT touch ATAC
    # here — ATAC is populated independently below from scATAnno).
    log_message("\nChecking RNA cell_type (fallback if per-sample write failed)...", LOG_FILE)
    if 'rna' in combined_mdata.mod:
        rna_obs = combined_mdata.mod['rna'].obs
        need_fallback = True
        if 'cell_type' in rna_obs.columns:
            vals = rna_obs['cell_type'].dropna().unique()
            if len(vals) >= 1:
                need_fallback = False
                log_message(
                    f"  RNA cell_type present: {rna_obs['cell_type'].nunique(dropna=True)} unique labels",
                    LOG_FILE,
                )
        if need_fallback:
            for candidate, src in _CT_CANDIDATES:
                if candidate in rna_obs.columns:
                    vals = rna_obs[candidate].dropna().unique()
                    if len(vals) > 1 or (len(vals) == 1 and str(vals[0]).lower() != 'unknown'):
                        rna_obs['cell_type'] = rna_obs[candidate].values
                        rna_obs['cell_type_source'] = src
                        log_message(
                            f"  RNA cell_type fallback: set from '{candidate}' (source={src})",
                            LOG_FILE,
                        )
                        break
            else:
                log_message(
                    "  WARN: no usable RNA cell_type column; leaving NaN",
                    LOG_FILE, "WARN",
                )

    # ========================================================================
    # ATAC-side cell_type from scATAnno (independent of RNA annotation)
    # ========================================================================
    # Both sides are normalized to (sample, stripped_barcode) to paper over
    # differing concat conventions: annot may use "sample:raw-GEM" or
    # "raw-GEM-sample"; mdata uses "sample:stripped". NaN on miss.
    if args.atac_annotations and Path(args.atac_annotations).exists():
        log_message("\nTransferring ATAC cell type annotations from annotated peak matrix...", LOG_FILE)
        try:
            atac_annot = sc.read_h5ad(args.atac_annotations, backed='r')
            atac_annot_obs = atac_annot.obs

            atac_ct_col = None
            for candidate in ['cell_type_prediction', 'celltypist_prediction', 'cell_type', 'pred_y']:
                if candidate in atac_annot_obs.columns:
                    vals = atac_annot_obs[candidate].dropna().unique()
                    if len(vals) > 1 or (len(vals) == 1 and str(vals[0]).lower() != 'unknown'):
                        atac_ct_col = candidate
                        break

            if atac_ct_col:
                # Detect sample column on the annot side
                annot_sample_col = None
                for c in ('batch', 'sample', 'sample_id'):
                    if c in atac_annot_obs.columns:
                        annot_sample_col = c
                        break
                annot_samples = (
                    atac_annot_obs[annot_sample_col].astype(str).values
                    if annot_sample_col is not None else [''] * atac_annot.n_obs
                )
                annot_preds = atac_annot_obs[atac_ct_col].astype(object).values

                annot_lookup = {}  # (sample, stripped_bc) -> label
                for obs_name, sample, label in zip(
                    atac_annot.obs_names, annot_samples, annot_preds
                ):
                    obs_name = str(obs_name)
                    # Handle "sample:raw-GEM" vs "raw-GEM-sample" vs "raw-GEM"
                    if ':' in obs_name:
                        s_prefix, bc_core = obs_name.split(':', 1)
                        if not sample:
                            sample = s_prefix
                    elif sample and obs_name.endswith(f'-{sample}'):
                        bc_core = obs_name[: -(len(sample) + 1)]
                    else:
                        bc_core = obs_name
                    stripped = _strip_gem(bc_core)
                    annot_lookup[(str(sample), stripped)] = label
                    annot_lookup[('', stripped)] = label

                atac_mod = combined_mdata.mod['atac']
                # Recover per-cell sample id from the MuData (atac mod was populated
                # with sample_id in the per-sample loop via combined_mdata.obs['sample_id'])
                atac_samples = combined_mdata.obs.loc[atac_mod.obs_names, 'sample_id'].astype(str).values
                atac_cell_types = []
                n_matched = 0
                for bc, sid in zip(atac_mod.obs_names, atac_samples):
                    bc = str(bc)
                    bc_core = bc.split(':', 1)[-1] if ':' in bc else bc
                    stripped = _strip_gem(bc_core)
                    lbl = annot_lookup.get((sid, stripped),
                                           annot_lookup.get(('', stripped)))
                    if lbl is not None and not pd.isna(lbl):
                        n_matched += 1
                        atac_cell_types.append(str(lbl))
                    else:
                        atac_cell_types.append(np.nan)

                atac_mod.obs['cell_type'] = atac_cell_types
                atac_mod.obs['cell_type_source'] = 'scatanno'
                combined_mdata.obs['atac_cell_type'] = atac_cell_types
                n_uniq = len({ct for ct in atac_cell_types if not pd.isna(ct)})
                log_message(
                    f"  Transferred '{atac_ct_col}' → atac:cell_type for "
                    f"{n_matched}/{len(atac_cell_types)} cells; {n_uniq} unique labels",
                    LOG_FILE,
                )
            else:
                log_message("  No usable cell type column found in annotated peak matrix", LOG_FILE, "WARN")

            del atac_annot
            gc.collect()
        except Exception as e:
            log_message(f"  Could not transfer ATAC annotations: {e}", LOG_FILE, "WARN")

    # ========================================================================
    # Unified MuData-level obs/cell_type: prefer RNA, fall back to ATAC, NaN otherwise
    # ========================================================================
    rna_ct = combined_mdata.mod['rna'].obs.get('cell_type') if 'rna' in combined_mdata.mod else None
    atac_ct = combined_mdata.mod['atac'].obs.get('cell_type') if 'atac' in combined_mdata.mod else None
    if rna_ct is not None or atac_ct is not None:
        unified = pd.Series(index=combined_mdata.obs_names, dtype=object)
        if rna_ct is not None:
            rna_ct_reidx = rna_ct.reindex(combined_mdata.obs_names)
            unified.loc[rna_ct_reidx.notna()] = rna_ct_reidx[rna_ct_reidx.notna()].astype(str).values
        if atac_ct is not None:
            atac_ct_reidx = atac_ct.reindex(combined_mdata.obs_names)
            fill_mask = unified.isna() & atac_ct_reidx.notna()
            unified.loc[fill_mask] = atac_ct_reidx[fill_mask].astype(str).values
        combined_mdata.obs['cell_type'] = unified.values
        # Record which source each cell's unified label came from
        source = pd.Series('none', index=combined_mdata.obs_names, dtype=object)
        if rna_ct is not None:
            source.loc[rna_ct.reindex(combined_mdata.obs_names).notna()] = 'rna'
        if atac_ct is not None:
            both_na_mask = source == 'none'
            atac_avail = atac_ct.reindex(combined_mdata.obs_names).notna()
            source.loc[both_na_mask & atac_avail] = 'atac'
        combined_mdata.obs['cell_type_source'] = source.values
        n_rna = int((source == 'rna').sum())
        n_atac = int((source == 'atac').sum())
        n_none = int((source == 'none').sum())
        log_message(
            f"Unified obs/cell_type: {n_rna} from RNA, {n_atac} from ATAC, {n_none} unlabeled",
            LOG_FILE,
        )

    log_message(f"\n Final MuData: {combined_mdata.n_obs:,} cells", LOG_FILE)
    log_memory(LOG_FILE)
    
    # ========================================================================
    # Save outputs with Nextflow-compatible names
    # ========================================================================
    log_message("\n" + "="*80, LOG_FILE)
    log_message("SAVING OUTPUTS", LOG_FILE)
    log_message("="*80, LOG_FILE)
    
    # Save main MuData file
    output_file = OUTPUT_DIR / args.output_name

    # --------------------------------------------------------------------
    # Ensure 'sample_id' exists in modality obs (needed by MultiVI)
    # --------------------------------------------------------------------
    if "sample_id" in combined_mdata.obs.columns:
        # Propagate to RNA modality
        rna_obs = combined_mdata.mod["rna"].obs
        if "sample_id" not in rna_obs.columns:
            rna_obs["sample_id"] = combined_mdata.obs.loc[rna_obs.index, "sample_id"].values
        
        # Propagate to ATAC modality (not strictly required for batch, but useful)
        atac_obs = combined_mdata.mod["atac"].obs
        if "sample_id" not in atac_obs.columns:
            atac_obs["sample_id"] = combined_mdata.obs.loc[atac_obs.index, "sample_id"].values
    else:
        raise RuntimeError("Expected 'sample_id' in combined_mdata.obs when building MuData")
    
    # Normalize RNA: store raw counts in .layers['counts'], log1p-normalize .X
    rna_mod = combined_mdata.mod['rna']
    if 'counts' not in rna_mod.layers:
        rna_mod.layers['counts'] = rna_mod.X.copy()
    sc.pp.normalize_total(rna_mod, target_sum=1e4)
    sc.pp.log1p(rna_mod)
    log_message("✓ RNA normalized (normalize_total + log1p), raw counts in .layers['counts']", LOG_FILE)

    # Normalize ATAC: store raw counts in .layers['counts'], log1p-normalize .X
    atac_mod = combined_mdata.mod['atac']
    if 'counts' not in atac_mod.layers:
        atac_mod.layers['counts'] = atac_mod.X.copy()
    sc.pp.normalize_total(atac_mod, target_sum=1e4)
    sc.pp.log1p(atac_mod)
    log_message("✓ ATAC normalized (normalize_total + log1p), raw counts in .layers['counts']", LOG_FILE)

    # Save main MuData file
    output_file = OUTPUT_DIR / args.output_name
    sanitize_mudata(combined_mdata, output_file)
    combined_mdata.write_h5mu(output_file)
    log_message(f"✓ Saved: {output_file}", LOG_FILE)
    
    # Save statistics as CSV
    stats_df = pd.DataFrame(sample_stats)
    stats_csv = OUTPUT_DIR / "sample_statistics.csv"
    stats_df.to_csv(stats_csv, index=False)
    log_message(f"✓ Saved statistics CSV: {stats_csv}", LOG_FILE)
    
    # NEW: Save statistics as JSON (Nextflow expects this)
    stats_json = {
        'n_samples': len(sample_stats),
        'total_cells': int(combined_mdata.n_obs),
        'total_rna_genes': int(combined_mdata.mod['rna'].n_vars),
        'total_atac_peaks': int(combined_mdata.mod['atac'].n_vars),
        'mean_cells_per_sample': float(stats_df['n_multiome'].mean()),
        'mean_retention_rate': float(stats_df['retention_rate'].mean()),
        'samples': sample_stats
    }
    
    stats_json_file = OUTPUT_DIR / "mudata_stats.json"
    with open(stats_json_file, 'w') as f:
        json.dump(stats_json, f, indent=2)
    log_message(f" Saved statistics JSON: {stats_json_file}", LOG_FILE)
    
    # Save integration summary
    summary = {
        'timestamp': datetime.now().isoformat(),
        'output_file': str(output_file),
        'total_samples': len(sample_stats),
        'total_cells': int(combined_mdata.n_obs),
        'total_rna_genes': int(combined_mdata.mod['rna'].n_vars),
        'total_atac_peaks': int(combined_mdata.mod['atac'].n_vars),
        'mean_cells_per_sample': float(stats_df['n_multiome'].mean()),
        'mean_retention_rate': float(stats_df['retention_rate'].mean()),
    }
    
    summary_file = OUTPUT_DIR / "integration_summary.json"
    with open(summary_file, 'w') as f:
        json.dump(summary, f, indent=2)
    log_message(f"✓ Saved summary: {summary_file}", LOG_FILE)
    
    # Cleanup temp directory
    if TEMP_DIR.exists():
        shutil.rmtree(TEMP_DIR)
    
    log_message("\n" + "="*80, LOG_FILE)
    log_message(" MUDATA CONSTRUCTION COMPLETE!", LOG_FILE)
    log_message("="*80, LOG_FILE)
    
    return 0

if __name__ == "__main__":
    sys.exit(main())

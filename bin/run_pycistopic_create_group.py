#!/usr/bin/env python
"""
run_pycistopic_create_group.py — Phase 2 of the pyCisTopic 3-phase pipeline.

Creates a CistopicObject for ONE (cell_type_safe × condition) group by reading
fragment files for only the barcodes belonging to that group (across all samples).
Memory footprint ∝ n_group_cells × n_peaks — typically 15-30 GB vs 135 GB for
the monolithic per-sample approach.

Output: {cell_type_safe}__{condition}_cistopic.pkl
"""

import argparse
import logging
import os
import pickle
import sys

import pandas as pd
import polars as pl
from pycisTopic.cistopic_class import create_cistopic_object_from_fragments


def setup_logger():
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)-8s %(message)s",
        stream=sys.stderr,
    )
    return logging.getLogger("pycistopic_create_group")


def parse_args():
    p = argparse.ArgumentParser(
        description="pyCisTopic Phase 2: create one CistopicObject per CT×condition group."
    )
    p.add_argument("--cell-type",      required=True, help="cell_type_safe label for this group.")
    p.add_argument("--condition",      required=True, help="Condition label for this group.")
    p.add_argument("--cell-metadata",  required=True,
                   help="cell_metadata_for_pycistopic.safe.tsv from Phase 1.")
    p.add_argument("--fragments-map",  required=True,
                   help="fragments_map.tsv from Phase 1.")
    p.add_argument("--consensus-bed",  required=True,
                   help="consensus_regions.bed from Phase 1.")
    p.add_argument("--qc-dir",         required=True,
                   help="qc/ directory from Phase 1 (contains per-sample parquets).")
    p.add_argument("--blacklist",      required=True,
                   help="Decompressed blacklist.bed from Phase 1.")
    p.add_argument("--sample-id-col",  default="sample_id")
    p.add_argument("--cell-type-col",  default="cell_type_safe")
    p.add_argument("--condition-col",  default="condition")
    p.add_argument("--n-cpu",          type=int, default=4)
    p.add_argument("--outdir",         required=True)
    return p.parse_args()


def _safe_fname(s):
    import re
    s = re.sub(r"[^A-Za-z0-9_.-]", "_", str(s))
    return re.sub(r"_+", "_", s).strip("_")


def main():
    args = parse_args()
    logger = setup_logger()
    os.makedirs(args.outdir, exist_ok=True)

    ct_safe = _safe_fname(args.cell_type)
    cond_safe = _safe_fname(args.condition)
    out_pkl = os.path.join(args.outdir, f"{ct_safe}__{cond_safe}_cistopic.pkl")
    logger.info("Creating CistopicObject for CT='%s' condition='%s'", args.cell_type, args.condition)

    # ── Load cell metadata ──────────────────────────────────────────────────
    cell_data = pd.read_table(args.cell_metadata, index_col=0, sep="\t")
    if "barcode" in cell_data.columns:
        cell_data.index = cell_data["barcode"].astype(str)

    # Normalise barcode index (strip sample prefix if present)
    raw_idx = cell_data.index.astype(str)
    if raw_idx.str.contains(":").any():
        cell_data.index = raw_idx.str.split(":", n=1).str[-1]

    # Filter to this group
    if args.condition_col in cell_data.columns:
        group_mask = (
            cell_data[args.cell_type_col].astype(str).eq(args.cell_type)
            & cell_data[args.condition_col].astype(str).eq(args.condition)
        )
    else:
        group_mask = cell_data[args.cell_type_col].astype(str).eq(args.cell_type)

    group_data = cell_data[group_mask].copy()
    logger.info("Group has %d cells across all samples.", len(group_data))

    if len(group_data) == 0:
        raise ValueError(
            f"No cells found for CT='{args.cell_type}' condition='{args.condition}'. "
            "Check that --cell-type and --condition match exactly."
        )

    # ── Load fragments map ──────────────────────────────────────────────────
    frag_map_df = pd.read_table(args.fragments_map, sep="\t")
    path_to_fragments = dict(zip(
        frag_map_df["sample_id"].astype(str),
        frag_map_df["fragments_path"].astype(str),
    ))

    # ── Per-sample CistopicObject creation ─────────────────────────────────
    sample_ids = sorted(group_data[args.sample_id_col].astype(str).unique())
    cistopic_objects = []

    for sid in sample_ids:
        if sid not in path_to_fragments:
            logger.warning("  %s: no fragment file — skipping.", sid)
            continue
        frag_path = path_to_fragments[sid]

        sample_barcodes = group_data[
            group_data[args.sample_id_col].astype(str) == sid
        ].index.tolist()

        if len(sample_barcodes) == 0:
            logger.info("  %s: 0 group barcodes in this sample — skipping.", sid)
            continue

        # Load pre-computed QC stats (generated by pycistopic qc in Phase 1)
        parquet_path = os.path.join(args.qc_dir, f"{sid}.fragments_stats_per_cb.parquet")
        if not os.path.exists(parquet_path):
            logger.warning("  %s: QC parquet missing at %s — skipping.", sid, parquet_path)
            continue

        stats_df = (
            pl.read_parquet(parquet_path)
            .to_pandas()
            .set_index("CB")
        )
        # Keep only group barcodes that appear in the QC stats
        bc_passing = [bc for bc in sample_barcodes if bc in stats_df.index]
        logger.info("  %s: %d/%d group barcodes found in QC stats.",
                    sid, len(bc_passing), len(sample_barcodes))

        if len(bc_passing) == 0:
            logger.warning("  %s: 0 barcodes after QC-stats intersection — skipping.", sid)
            continue

        sample_metrics = stats_df.loc[bc_passing]

        logger.info("  %s: calling create_cistopic_object_from_fragments (%d cells × consensus peaks)...",
                    sid, len(bc_passing))
        obj = create_cistopic_object_from_fragments(
            path_to_fragments=frag_path,
            path_to_regions=args.consensus_bed,
            path_to_blacklist=args.blacklist,
            metrics=sample_metrics,
            valid_bc=bc_passing,
            n_cpu=1,
            project=sid,
            split_pattern="-",
        )
        logger.info("  %s: created CistopicObject with %d cells.", sid, len(obj.cell_names))
        cistopic_objects.append(obj)

    if len(cistopic_objects) == 0:
        raise ValueError(
            f"No CistopicObjects created for CT='{args.cell_type}' condition='{args.condition}'."
        )

    # ── Merge per-sample objects for this group ─────────────────────────────
    if len(cistopic_objects) == 1:
        merged = cistopic_objects[0]
        logger.info("Single sample — %d cells total.", len(merged.cell_names))
    else:
        merged = cistopic_objects[0].merge(
            cistopic_objects[1:],
            is_acc=1,
            project=f"{ct_safe}__{cond_safe}",
            copy=True,
            split_pattern="-",
        )
        logger.info("Merged %d samples — %d cells total.",
                    len(cistopic_objects), len(merged.cell_names))

    # ── Save ────────────────────────────────────────────────────────────────
    with open(out_pkl, "wb") as f:
        pickle.dump(merged, f)
    logger.info("Saved CistopicObject to %s", out_pkl)


if __name__ == "__main__":
    main()
